<?php

namespace App\\Console\\Commands;

use Illuminate\\Console\\Command;

class ValidateOfferingGapAuditArtifact extends Command
{
    protected $signature = 'institutes:offering-gap-artifact-validate {file : JSON report generated by offering-gap reconciliation} {--expected-rows=36 : Expected register row count} {--json : Print machine-readable JSON}';
    protected $description = 'Validate the structure and read-only safety markers of an offering-gap audit artifact.';

    public function handle(): int
    {
        $result=['check'=>'offering_gap_artifact_validation','mode'=>'read_only','mutation_performed'=>false,'database_mutations'=>0,'status'=>'BLOCKED','errors'=>[],'summary'=>[]];
        $path=(string)$this->argument('file');
        if (!is_file($path)||!is_readable($path)) $result['errors'][]='artifact_missing_or_unreadable';
        else {
            $decoded=json_decode((string)file_get_contents($path),true);
            if (!is_array($decoded)) $result['errors'][]='artifact_invalid_json';
            else {
                foreach (['summary','records','mutation_performed','database_mutations','production_write_authorization'] as $key) if (!array_key_exists($key,$decoded)) $result['errors'][]='required_artifact_field_missing:'.$key;
                if (($decoded['mutation_performed']??null)!==false) $result['errors'][]='mutation_marker_not_false';
                if (($decoded['database_mutations']??null)!==0) $result['errors'][]='database_mutations_not_zero';
                if (($decoded['production_write_authorization']??null)!==false) $result['errors'][]='production_write_authorization_not_false';
                if (isset($decoded['records'])&&!is_array($decoded['records'])) $result['errors'][]='records_not_array';
                $count=is_array($decoded['records']??null)?count($decoded['records']):0;
                $expected=max(0,(int)$this->option('expected-rows'));
                $result['summary']=['record_count'=>$count,'expected_record_count'=>$expected,'record_count_matches_expected'=>$count===$expected,'source_status'=>$decoded['reconciliation_status']??null];
                if ($count!==$expected) $result['errors'][]='record_count_mismatch';
                if (is_array($decoded['records']??null)) foreach ($decoded['records'] as $index=>$record) {
                    if (!is_array($record)||!array_key_exists('classification',$record)||!array_key_exists('blockers',$record)||!array_key_exists('canonical_mutation_performed',$record)) $result['errors'][]='record_schema_invalid_at_index:'.$index;
                    elseif ($record['canonical_mutation_performed']!==false) $result['errors'][]='record_mutation_marker_not_false_at_index:'.$index;
                }
            }
        }
        $result['status']=$result['errors']===[]?'ARTIFACT_VALID_REVIEW_REQUIRED':'BLOCKED';
        if ($this->option('json')) $this->line(json_encode($result,JSON_PRETTY_PRINT|JSON_UNESCAPED_SLASHES));
        else { $this->table(['Metric','Value'],collect($result['summary'])->map(fn($v,$k)=>[$k,$v])->values()->all()); $this->info('status='.$result['status']); $this->line('database_mutations=0'); }
        return $result['errors']===[]?self::SUCCESS:self::FAILURE;
    }
}